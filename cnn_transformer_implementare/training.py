from __future__ import annotations

from pathlib import Path

import numpy as np
import torch
from model import CNNTransformer, augment_batch
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.preprocessing import StandardScaler
from torch import nn
from torch.utils.data import DataLoader, TensorDataset

TensorPair = tuple[torch.Tensor, torch.Tensor]

def train_model(

    model: CNNTransformer,

    train_data: TensorPair,

    val_data: TensorPair,

    best_model_path: Path,

    device: torch.device,

    epochs: int,

    batch_size: int,

    learning_rate: float,

    patience: int,

) -> tuple[CNNTransformer, dict[str, list[float]]]:

    model = model.to(device)

    optimizer = torch.optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=1e-3)

    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    loss_fn = nn.HuberLoss(delta=1.0)

    x_train, y_train = train_data

    x_val, y_val = val_data

    loader = DataLoader(TensorDataset(x_train, y_train), batch_size = batch_size, shuffle = True)

    best_val_loss = float("inf")

    patience_counter = 0

    history: dict[str, list[float]] = {"train": [], "val": []}

    for epoch in range(epochs):

        # set the model for training mode
        model.train()

        train_losses = []

        for features, targets in loader:

            features, targets = augment_batch(features.to(device), targets.to(device))

            # model predictions
            predictions = model(features)

            # loss generated by the model
            loss = loss_fn(predictions, targets)

            # clear the accumulated previous graients
            optimizer.zero_grad()

            # calculate the new gradients - backpropagation
            loss.backward()

            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)

            # update the model
            optimizer.step()

            # save the loss for monitoring
            train_losses.append(loss.item())

        # update the learning rate
        scheduler.step()

        model.eval()

        with torch.no_grad():
            val_loss = loss_fn(model(x_val.to(device)), y_val.to(device)).item()

        history["train"].append(float(np.mean(train_losses)))
        history["val"].append(val_loss)

        if val_loss < best_val_loss:
            best_val_loss = val_loss

            patience_counter = 0

            torch.save(model.state_dict(), best_model_path)
        else:
            patience_counter += 1

            if patience_counter >= patience:
                print(f"Early stopping at epoch {epoch}.")
                break

        if epoch % 25 == 0:
            print(
                f"Epoch {epoch:3d} | train={np.mean(train_losses):.4f} | val={val_loss:.4f}"
            )

    model.load_state_dict(torch.load(best_model_path, map_location=device))
    return model, history


def predict_um(
    model: CNNTransformer,
    features: torch.Tensor,
    y_scaler: StandardScaler,
    device: torch.device,
) -> np.ndarray:
    """
        Predict concentrations in uM from normalized log-target outputs.
    """

    model.eval()

    with torch.no_grad():
        predictions = model(features.to(device)).cpu().numpy()

    log_predictions = y_scaler.inverse_transform(predictions.reshape(-1, 1)).ravel()

    return np.exp(log_predictions)

def regression_metrics(truth: np.ndarray, predictions: np.ndarray) -> dict[str, float]:
    return {
        "MAE": float(mean_absolute_error(truth, predictions)),
        "RMSE": float(np.sqrt(mean_squared_error(truth, predictions))),
        "R2": float(r2_score(truth, predictions)),
        "MAPE": float(np.mean(np.abs((truth - predictions) / truth)) * 100),
    }

def evaluate(
    model: CNNTransformer,
    features: torch.Tensor,
    truth: np.ndarray,
    y_scaler: StandardScaler,
    device: torch.device,
    name: str,
) -> tuple[dict[str, float], np.ndarray]:
    predictions = predict_um(model, features, y_scaler, device)
    metrics = regression_metrics(truth, predictions)
    print(f"\n{name} metrics:")
    print(f"  MAE:  {metrics['MAE']:7.2f} uM")
    print(f"  RMSE: {metrics['RMSE']:7.2f} uM")
    print(f"  R2:   {metrics['R2']:7.4f}")
    print(f"  MAPE: {metrics['MAPE']:7.2f}%")
    return metrics, predictions
